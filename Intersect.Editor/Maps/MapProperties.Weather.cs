using System.ComponentModel;
using Intersect.Editor.General;
using Intersect.Editor.Localization;
using Intersect.Framework.Core.GameObjects.Animations;
using Intersect.Framework.Core.QualityOfLife;
namespace Intersect.Editor.Maps;
internal sealed class WeatherLabelAttribute(string name):DisplayNameAttribute(name)
{
    public override string DisplayName=>QualityOfLifeText.Get(DisplayNameValue,System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName);
}
internal sealed class WeatherHelpAttribute(string text):DescriptionAttribute(text)
{
    public override string Description=>QualityOfLifeText.Get(DescriptionValue,System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName);
}
partial class MapProperties
{
    private void ChangeWeather(Action update)
    {
        Globals.MapEditorWindow.PrepUndoState();update();Globals.MapEditorWindow.AddUndoState();
    }
    [CustomCategory("weather"),WeatherLabel("Random weather (15 minutes)"),DefaultValue(true)]
    public bool RandomWeather {get=>mMyMap.WeatherEffects.RandomWeather;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RandomWeather=value);}
    [CustomCategory("weather"),WeatherLabel("Rain generated by the engine"),DefaultValue(true),
     WeatherHelp("Generates rain without an animation. Uses weather intensity and wind; zero vertical speed uses the default fall speed. Ground splashes and random weather are optional.")]
    public bool WeatherGeneratedRain
    {
        get=>mMyMap.WeatherEffects.GeneratedRain;
        set=>ChangeWeather(()=>
        {
            mMyMap.WeatherEffects.GeneratedRain=value;
            if(value && mMyMap.WeatherIntensity==0)mMyMap.WeatherIntensity=50;
        });
    }
    [CustomCategory("weather"),WeatherLabel("Rain sound (loop)"),TypeConverter(typeof(MapSoundProperty))]
    public string WeatherRainSound
    {
        get=>string.IsNullOrWhiteSpace(mMyMap.WeatherEffects.RainSound)?Strings.General.None:mMyMap.WeatherEffects.RainSound;
        set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainSound=value==Strings.General.None?"":value);
    }
    [CustomCategory("weather"),WeatherLabel("Thunder sound"),TypeConverter(typeof(MapSoundProperty))]
    public string WeatherThunderSound
    {
        get=>string.IsNullOrWhiteSpace(mMyMap.WeatherEffects.ThunderSound)?Strings.General.None:mMyMap.WeatherEffects.ThunderSound;
        set=>ChangeWeather(()=>mMyMap.WeatherEffects.ThunderSound=value==Strings.General.None?"":value);
    }
    [CustomCategory("weather"),WeatherLabel("Puddle drying time (minutes)"),DefaultValue(3)]
    public int WeatherPuddleDryMinutes
    {
        get=>mMyMap.WeatherEffects.PuddleDryMinutes;
        set=>ChangeWeather(()=>mMyMap.WeatherEffects.PuddleDryMinutes=Math.Clamp(value,1,30));
    }
    [CustomCategory("weather"),WeatherLabel("Change fog during rain"),DefaultValue(false)]
    public bool WeatherOverrideRainFog {get=>mMyMap.WeatherEffects.OverrideRainFog;set=>ChangeWeather(()=>mMyMap.WeatherEffects.OverrideRainFog=value);}
    [CustomCategory("weather"),WeatherLabel("Rain fog"),TypeConverter(typeof(MapFogProperty))]
    public string WeatherRainFog {get=>string.IsNullOrWhiteSpace(mMyMap.WeatherEffects.RainFog)?Strings.General.None:mMyMap.WeatherEffects.RainFog;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainFog=value==Strings.General.None?"":value);}
    [CustomCategory("weather"),WeatherLabel("Rain fog opacity (0-255)"),DefaultValue(100)]
    public int WeatherRainFogOpacity {get=>mMyMap.WeatherEffects.RainFogOpacity;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainFogOpacity=Math.Clamp(value,0,255));}
    [CustomCategory("weather"),WeatherLabel("Rain fog X speed"),DefaultValue(0)]
    public int WeatherRainFogXSpeed {get=>mMyMap.WeatherEffects.RainFogXSpeed;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainFogXSpeed=Math.Clamp(value,-5,5));}
    [CustomCategory("weather"),WeatherLabel("Rain fog Y speed"),DefaultValue(0)]
    public int WeatherRainFogYSpeed {get=>mMyMap.WeatherEffects.RainFogYSpeed;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainFogYSpeed=Math.Clamp(value,-5,5));}
    [CustomCategory("weather"),WeatherLabel("Change brightness during rain"),DefaultValue(false)]
    public bool WeatherOverrideRainBrightness {get=>mMyMap.WeatherEffects.OverrideRainBrightness;set=>ChangeWeather(()=>mMyMap.WeatherEffects.OverrideRainBrightness=value);}
    [CustomCategory("weather"),WeatherLabel("Rain brightness (%)"),DefaultValue(70)]
    public int WeatherRainBrightness {get=>mMyMap.WeatherEffects.RainBrightness;set=>ChangeWeather(()=>mMyMap.WeatherEffects.RainBrightness=Math.Clamp(value,0,100));}
    [CustomCategory("weather"),WeatherLabel("Storm flashes"),DefaultValue(true)]
    public bool WeatherFlashes {get=>mMyMap.WeatherEffects.Flashes;set=>ChangeWeather(()=>mMyMap.WeatherEffects.Flashes=value);}
    [CustomCategory("weather"),WeatherLabel("Flash opacity (%)"),DefaultValue(25)]
    public int WeatherFlashOpacity {get=>mMyMap.WeatherEffects.FlashOpacity;set=>ChangeWeather(()=>mMyMap.WeatherEffects.FlashOpacity=Math.Clamp(value,0,80));}
    [CustomCategory("weather"),WeatherLabel("Lightning bolts"),DefaultValue(true)]
    public bool WeatherLightning {get=>mMyMap.WeatherEffects.Lightning;set=>ChangeWeather(()=>mMyMap.WeatherEffects.Lightning=value);}
    [CustomCategory("weather"),WeatherLabel("Lightning animation"),TypeConverter(typeof(MapWeatherProperty))]
    public string WeatherLightningAnimation
    {
        get=>AnimationDescriptor.Get(mMyMap.WeatherEffects.LightningAnimationId)?.Name??Strings.General.None;
        set=>ChangeWeather(()=>mMyMap.WeatherEffects.LightningAnimationId=AnimationDescriptor.Lookup.Values.FirstOrDefault(a=>a.Name==value)?.Id??Guid.Empty);
    }
    [CustomCategory("weather"),WeatherLabel("Ground splashes"),DefaultValue(true)]
    public bool WeatherGroundSplashes {get=>mMyMap.WeatherEffects.GroundSplashes;set=>ChangeWeather(()=>mMyMap.WeatherEffects.GroundSplashes=value);}
    [CustomCategory("weather"),WeatherLabel("Splash animation"),TypeConverter(typeof(MapWeatherProperty))]
    public string WeatherSplashAnimation
    {
        get=>AnimationDescriptor.Get(mMyMap.WeatherEffects.SplashAnimationId)?.Name??Strings.General.None;
        set=>ChangeWeather(()=>mMyMap.WeatherEffects.SplashAnimationId=AnimationDescriptor.Lookup.Values.FirstOrDefault(a=>a.Name==value)?.Id??Guid.Empty);
    }
}
