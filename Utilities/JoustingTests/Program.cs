using Intersect.Framework.Core.Jousting;
var count = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); count++; Console.WriteLine("PASS " + name); }
var rules = new JoustRules { UnhorseEndsMatch = false };
JoustMatch Match(bool pve = true) => new(rules, 0, JoustDifficulty.Knight, pve, 123);
var startAim = rules.PreparationMs + rules.ChargeMs;
var impact = startAim + rules.AimMs;
var match = Match();
Check(!match.Submit(0, 1, 0, new(.5, .45, false), 100), "input before aim rejected");
match.Advance(startAim);
Check(match.Phase == JoustPhase.Aim, "exact boundary enters aim");
Check(!match.Submit(0, 1, 0, new(double.NaN, .5, false), startAim + 50), "NaN rejected");
Check(!match.Submit(0, 1, 0, new(.5, double.PositiveInfinity, false), startAim + 50), "infinity rejected");
Check(!match.Submit(0, 1, 0, new(-.1, .5, false), startAim + 50), "outside target rejected");
Check(!match.Submit(0, 2, 0, new(.5, .45, false), startAim + 50), "wrong pass rejected");
Check(!match.Submit(1, 1, 0, new(.5, .45, false), startAim + 50), "client cannot drive AI");
Check(match.Submit(0, 1, 0, new(.5, .45, false), startAim + 100), "valid input accepted");
Check(match.Aim(0).Y > .45, "lance speed bounded");
Check(!match.Submit(0, 1, 0, new(.5, .45, false), startAim + 200), "replay rejected");
Check(!match.Submit(0, 1, 1, new(.5, .45, false), startAim + 120), "flood rejected");
match.Submit(0, 1, 1, new(.5, .45, false), startAim + 300);
match.Submit(0, 1, 2, new(.5, .45, false), startAim + 500);
Check(!match.Submit(0, 1, 3, new(.5, .45, false), impact), "exact impact refuses late input");
Check(match.Phase == JoustPhase.Impact, "server resolves without client confirmation");
var scored = match.Scores.Sum(); match.Advance(impact + 1); Check(match.Scores.Sum() == scored, "impact scored once");
var idle = Match(false); idle.Advance(1000000); Check(idle.Done && idle.Scores.Sum() == 0 && idle.Pass == 3, "idle cannot score and stalled clients cannot delay match");
var simultaneous = Match(false);
for (var step = 1; step <= 5; step++)
    for (var side = 0; side < 2; side++) simultaneous.Submit(side, 1, step, new(.5, .45, false), startAim + step * 100);
simultaneous.Advance(impact);
Check(simultaneous.Strikes[0].Hit == JoustHit.Unhorsed && simultaneous.Strikes[1].Hit == JoustHit.Unhorsed, "simultaneous attacks resolved before effects");
Check(simultaneous.Scores[0] == 3 && simultaneous.Scores[1] == 3, "torso 2 plus valid broken lance 1 follows V2 scoring");
var forbidden = Match(false);
for (var step = 1; step <= 6; step++) forbidden.Submit(0, 1, step, new(.5, .1, false), startAim + step * 100);
forbidden.Advance(impact); Check(forbidden.Scores[0] == 0, "head hit never rewarded");
var fine = Match(); var coarse = Match();
for (var t = 0; t <= 100000; t += 50) fine.Advance(t);
coarse.Advance(100000);
Check(fine.Scores.SequenceEqual(coarse.Scores) && fine.Phase == coarse.Phase, "AI independent of tick grouping");
var abandoned = Match(); abandoned.Abandon(0); abandoned.Advance(100000);
Check(abandoned.Phase == JoustPhase.Abandoned && abandoned.Winner == 1 && abandoned.Scores.Sum() == 0, "abandon releases active simulation");
var frozen = Match(); rules.Passes = 9; frozen.Advance(1000000); Check(frozen.Pass == 3, "active match freezes editor rules"); rules.Passes = 3;
var back = Match(); back.Advance(startAim + 500); back.Advance(0); Check(back.Phase == JoustPhase.Aim, "clock rollback does not reopen phase");
bool Invalid(string json) { try { JoustConfiguration.FromJson(json); return false; } catch { return true; } }
Check(Invalid("{\"Arenas\":null}"), "null arenas rejected");
Check(Invalid("{\"Arenas\":[null]}"), "null arena rejected");
var arena = new JoustArena();
var config = new JoustConfiguration { Arenas = [arena] };
Check(JoustConfiguration.FromJson(config.ToJson()).Arenas[0].Id == arena.Id, "configuration round trip");
config.Arenas = [arena, arena]; Check(!config.IsValid, "duplicate arena rejected");
arena.Enabled = true; Check(!arena.IsValid, "enabled arena requires map");
var lane = new JoustArena { MapId = Guid.NewGuid() };
var race = new JoustMatch(rules, 0, JoustDifficulty.Knight, false);
race.Advance(rules.PreparationMs);
var pose = JoustTrack.Sample(lane, race, rules.PreparationMs);
Check(pose.PlayerX == lane.StartX + 1 && pose.OpponentX == lane.EndX - 1, "both horses begin native interpolation together");
Check(pose.PlayerX + pose.OpponentX == lane.StartX + lane.EndX, "charge uses mirrored positions");
race.Advance(startAim);
pose = JoustTrack.Sample(lane, race, impact);
Check(pose.PlayerX == 15 && pose.OpponentX == 15, "aim ends at the shared impact midpoint");
race.Advance(impact);
pose = JoustTrack.Sample(lane, race, impact);
Check(pose.PlayerX == 16 && pose.OpponentX == 14 && pose.StepMilliseconds == 236, "runout interpolation begins at impact");
race.Advance(impact + rules.ImpactMs + rules.ResultsMs);
pose = JoustTrack.Sample(lane, race, race.PhaseStarted);
Check(race.Pass == 2 && pose.PlayerX == lane.EndX && pose.OpponentX == lane.StartX, "next pass starts at previous endpoints without a warp");
lane.EndX++; Check(!lane.IsValid, "odd lane length cannot place an integer impact midpoint"); lane.EndX--;
lane.OpponentY = lane.StartY; Check(!lane.IsValid, "horses cannot share one physical lane");
var waiting = Match(); waiting.HoldPreparation(5000); waiting.Advance(6999);
Check(waiting.Phase == JoustPhase.Preparation && waiting.Deadline == 7000, "native cinematic hold postpones the server countdown");
waiting.Advance(7000); Check(waiting.Phase == JoustPhase.Charge, "charge resumes when the held preparation expires");
Check(!rules.BodyTarget.Contains(.5, .32) && !rules.ShieldTarget.Contains(.5, .32), "frontal helmet pixels are outside legal targets");
Check(!rules.BodyTarget.Contains(.5, .58) && !rules.ShieldTarget.Contains(.5, .58), "frontal horse pixels are outside legal targets");
var horse = Match(false);
for (var step = 1; step <= 6; step++) horse.Submit(0, 1, step, new(.5, .58, false), startAim + step * 100);
horse.Advance(impact); Check(horse.Scores[0] == 0 && !horse.Strikes[0].BrokenLance, "horse contact earns neither points nor break bonus");
var creeping = Match(false); long creepingSequence = 0;
for (var step = 1; step <= 6; step++) creeping.Submit(0, 1, creepingSequence++, new(.48, .45, false), startAim + step * 100);
for (var step = 0; step < 12; step++) creeping.Submit(0, 1, creepingSequence++, new(.48 + step * .004, .45, false), impact - 600 + step * 50);
creeping.Advance(impact); Check(!creeping.Strikes[0].BrokenLance, "many small aim corrections cannot manufacture stability");
Console.WriteLine($"{count} checks passed.");
